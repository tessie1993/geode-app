#!/usr/bin/env python3
"""Writes core/library/JvmCase.inc: the simple case mappings core/library/JvmText.hpp reads.

Character.toLowerCase (every plane, as String.lowercase() applies it) and Character.toUpperCase on the
Basic Multilingual Plane (Kotlin's Char.equals(ignoreCase) compares one UTF-16 unit at a time). A letter
whose full mapping is more than one character keeps itself here, except U+0130, whose simple lower case
is i. Each row is a run: first, last, the delta added, and the stride between the letters it covers.

    python3 tools/jvm_case.py
"""
import pathlib


def mapping(limit: int, of) -> list:
    pairs = []
    for cp in range(limit):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        to = of(chr(cp))
        if len(to) == 1 and to != chr(cp):
            pairs.append((cp, ord(to)))
    return pairs


def runs(pairs: list) -> list:
    out = []
    for cp, to in pairs:
        delta = to - cp
        if out:
            first, last, d, stride = out[-1]
            step = cp - last
            if d == delta and ((stride == 0 and step in (1, 2)) or step == stride):
                out[-1] = [first, cp, d, stride or step]
                continue
        out.append([cp, cp, delta, 0])
    return [(f, l, d, s or 1) for f, l, d, s in out]


def table(name: str, rows: list) -> str:
    body = "\n".join(f"    {{0x{f:05X}, 0x{l:05X}, {d}, {s}}}," for f, l, d, s in rows)
    return f"inline constexpr CaseRun {name}[] = {{\n{body}\n}};\n"


def main() -> None:
    lower = dict(mapping(0x110000, str.lower))
    lower[0x130] = ord("i")
    upper = mapping(0x10000, str.upper)
    out = pathlib.Path(__file__).resolve().parent.parent / "core" / "library" / "JvmCase.inc"
    header = "// Generated by tools/jvm_case.py; do not edit. Runs sorted by first code point.\n"
    text = header + table("kLowerRuns", runs(sorted(lower.items()))) + table("kUpperRuns", runs(upper))
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"{out}: {len(lower)} lower, {len(upper)} upper")


if __name__ == "__main__":
    main()
