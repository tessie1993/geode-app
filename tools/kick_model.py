#!/usr/bin/env python3
"""The kick model's trees, from fosfora's trained ensemble into the engine's table.

Writes core/sound/KickModelTable.inc from fosfora's crates/fosfora-app/src/audio/kick_model.json
(tessie1993/fosforatess at 2e85d3b, board #3624): a gradient-boosted ensemble of 300 trees over 72 inputs,
24 spectral features of a hop and of the two hops before it (core/sound/KickModel.hpp says which). It
scores the probability that a hop holds a kick drum's attack, and rejects what the low bands alone cannot:
a bass note on the "and" rises there just like a kick.

The JSON is fosfora's, not ours, so it is read from a fosfora checkout rather than copied here; the table
keeps every number at float precision (%.9g round-trips a float), so a node compares exactly as fosfora's
f32 `x[f] <= threshold` does.

Node layout: {threshold or leaf value, left, right, feature}; feature 255 marks a leaf.

Run: python3 tools/kick_model.py <fosfora checkout>
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
INC = os.path.join(HERE, "..", "core", "sound", "KickModelTable.inc")
SOURCE = os.path.join("crates", "fosfora-app", "src", "audio", "kick_model.json")
N_INPUT = 72
LEAF = 255


def f32(x):
    s = f"{x:.9g}"
    if not any(c in s for c in ".en"):
        s += ".0"  # 0f is no float literal; 0.0f is
    return s + "f"


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    with open(os.path.join(sys.argv[1], SOURCE)) as src:
        e = json.load(src)
    assert e["format"] == 1, "kick_model.json format"
    assert e["n_features"] == N_INPUT, "kick_model.json was trained on other features"
    n = len(e["leaf"])
    assert n < 65536 and all(f < LEAF for f in e["feature"])
    with open(INC, "w") as out:
        out.write("// Generated by tools/kick_model.py from fosfora's kick_model.json. Do not edit: edit the script.\n")
        out.write(f"// {len(e['roots'])} trees, {n} nodes: {{threshold or leaf value, left, right, feature (255 = leaf)}}.\n")
        out.write("#ifdef GEODE_KICK_MODEL_HEADER\n")
        out.write(f"constexpr float kKickBaseline = {f32(e['baseline'])};\n")
        out.write(f"constexpr float kKickThreshold = {f32(e['kick_threshold'])};\n")
        out.write(f"constexpr int kKickTrees = {len(e['roots'])};\n")
        out.write(f"constexpr int kKickNodes = {n};\n")
        out.write("#endif\n")
        out.write("#ifdef GEODE_KICK_MODEL_ROOTS\n")
        roots = e["roots"]
        for i in range(0, len(roots), 16):
            out.write(", ".join(str(r) for r in roots[i:i + 16]) + ",\n")
        out.write("#endif\n")
        out.write("#ifdef GEODE_KICK_MODEL_NODES\n")
        for i in range(n):
            if e["leaf"][i]:
                out.write(f"{{{f32(e['value'][i])}, 0, 0, {LEAF}}},\n")
            else:
                out.write(f"{{{f32(e['threshold'][i])}, {e['left'][i]}, {e['right'][i]}, {e['feature'][i]}}},\n")
        out.write("#endif\n")


if __name__ == "__main__":
    main()
