#!/usr/bin/env python3
"""Generate app/src/main/java/dev/geode/ui/theme/MaterialSymbols.kt from Material Symbols Rounded.

Run from the repo root: python3 tools/material_symbols.py
Needs the network once, at authoring time; the app itself stays offline (the paths are compiled
in as Kotlin, no font file and no download at run time).

Each symbol is fetched twice from Google Fonts' static icon host, weight 400, grade 0, optical
size 24: the outlined form (FILL 0) and the filled form (FILL 1). The icons are Apache 2.0
(https://github.com/google/material-design-icons). To add one, add a row to SYMBOLS (the
StoneIcon name and the Material Symbols name) and run this again; then add the matching
StoneIcon entry.
"""

import os
import re
import urllib.request

# (StoneIcon name, Material Symbols name); right-to-left mirroring is set on the StoneIcon entry.
SYMBOLS = [
    ("ADD", "add"),
    ("CAST", "cast"),
    ("CHECK", "check"),
    ("CHEVRON_LEFT", "chevron_left"),
    ("CHEVRON_RIGHT", "chevron_right"),
    ("CLOSE", "close"),
    ("CROWN", "crown"),
    ("DELETE", "delete"),
    ("EDIT", "edit"),
    ("EXPAND", "expand_more"),
    ("FAVORITE", "favorite"),
    ("FILE", "draft"),
    ("FOLDER", "folder"),
    ("FULLSCREEN", "fullscreen"),
    ("LIBRARY", "library_music"),
    ("LYRICS", "notes"),
    ("MICROPHONE", "mic"),
    ("MORE", "more_vert"),
    ("NEXT", "skip_next"),
    ("PAUSE", "pause"),
    ("PLAY", "play_arrow"),
    ("PREVIOUS", "skip_previous"),
    ("QUEUE", "queue_music"),
    ("RECORD", "fiber_manual_record"),
    ("REPEAT", "repeat"),
    ("REPEAT_ONE", "repeat_one"),
    ("SEARCH", "search"),
    ("SETTINGS", "settings"),
    ("SHARE", "share"),
    ("SHUFFLE", "shuffle"),
    ("STOP", "stop_circle"),
    ("STUDIO", "movie"),
    ("VISUALIZER", "visibility"),
]

URL = "https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsrounded/{name}/{variant}/24px.svg"
OUT = os.path.join("app", "src", "main", "java", "dev", "geode", "ui", "theme", "MaterialSymbols.kt")
CHUNK = 96


def fetch_path(name, variant):
    with urllib.request.urlopen(URL.format(name=name, variant=variant), timeout=30) as response:
        svg = response.read().decode("utf-8")
    paths = re.findall(r'<path d="([^"]+)"', svg)
    if len(paths) != 1 or 'viewBox="0 -960 960 960"' not in svg:
        raise SystemExit(f"{name}/{variant}: expected one path on the 0 -960 960 960 grid")
    return paths[0]


def kotlin_string(path):
    chunks = [path[i : i + CHUNK] for i in range(0, len(path), CHUNK)]
    # The + ends each line: a line that starts with + would be a new statement in Kotlin.
    return " +\n".join(("        " if i == 0 else "            ") + f'"{chunk}"' for i, chunk in enumerate(chunks))


def camel(name):
    return "".join(part.capitalize() for part in name.lower().split("_"))


def main():
    lines = [
        "// Generated by tools/material_symbols.py from Material Symbols Rounded (Apache 2.0). Do not edit.",
        "package dev.geode.ui.theme",
        "",
        "/** Path data of each [StoneIcon], outlined (FILL 0) and filled (FILL 1), on the 0 -960 960 960 grid. */",
        "internal object MaterialSymbols {",
    ]
    for stone, name in SYMBOLS:
        outlined = fetch_path(name, "default")
        filled = fetch_path(name, "fill1")
        lines.append(f"    // {name}")
        lines.append(f"    const val {stone}_OUTLINED =")
        lines.append(kotlin_string(outlined))
        # Line symbols (add, check, close...) have no filled form; share the one path.
        if filled == outlined:
            lines.append(f"    const val {stone}_FILLED = {stone}_OUTLINED")
        else:
            lines.append(f"    const val {stone}_FILLED =")
            lines.append(kotlin_string(filled))
        lines.append("")
    lines[-1] = "}"
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(SYMBOLS)} symbols)")


if __name__ == "__main__":
    main()
