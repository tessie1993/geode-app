#!/usr/bin/env python3
"""Writes core/library/SearchFold.inc: the letters a library search folds to something else.

Each row is a code point and the one or two code points it is searched as: lower case, accents gone
(NFD without the marks), and the letters NFD leaves whole spelled the way people type them
(ß ss, æ ae, œ oe, þ th, ø o, ł l, đ ð d, ı i). ASCII is folded in code, not here.

    python3 tools/search_fold.py
"""
import pathlib
import unicodedata

RANGES = [(0xC0, 0x250), (0x370, 0x400), (0x400, 0x460), (0x1E00, 0x1F00)]
SPELLED = {"ß": "ss", "æ": "ae", "œ": "oe", "ø": "o", "ł": "l", "đ": "d", "ð": "d", "þ": "th", "ı": "i", "ς": "σ"}


def fold(ch: str) -> str:
    bare = "".join(c for c in unicodedata.normalize("NFD", ch) if unicodedata.category(c) != "Mn")
    return "".join(SPELLED.get(c, c) for c in bare.lower())


def main() -> None:
    rows = []
    for lo, hi in RANGES:
        for cp in range(lo, hi):
            ch = chr(cp)
            if unicodedata.category(ch)[0] != "L":
                continue
            to = fold(ch)
            if to == ch:
                continue
            assert 1 <= len(to) <= 2, (hex(cp), to)
            second = ord(to[1]) if len(to) == 2 else 0
            rows.append(f"{{0x{cp:04X}, {{0x{ord(to[0]):04X}, 0x{second:04X}}}}},  // {ch} {to}")
    out = pathlib.Path(__file__).resolve().parent.parent / "core" / "library" / "SearchFold.inc"
    header = "// Generated by tools/search_fold.py; do not edit. Sorted by code point.\n"
    out.write_text(header + "\n".join(rows) + "\n", encoding="utf-8")
    print(f"{out}: {len(rows)} rows")


if __name__ == "__main__":
    main()
